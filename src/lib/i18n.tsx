export function detectBrowserLanguage(): { code: string; language: Language; autoDetected: boolean } {
  // 1. Check if user already explicitly saved a language
  const savedCode = localStorage.getItem('imchat_language');
  if (savedCode) {
    const matched = LANGUAGES.find(l => l.code.toLowerCase() === savedCode.toLowerCase());
    if (matched) {
      return { code: matched.code, language: matched, autoDetected: false };
    }
  }

  // 2. Automatically detect from browser / device
  if (typeof navigator !== 'undefined') {
    const rawLangs = [
      navigator.language,
      ...(navigator.languages || [])
    ].filter(Boolean);

    for (const raw of rawLangs) {
      const clean = raw.toLowerCase().trim();
      
      // Exact code match (e.g. "zh-TW", "pt", "es")
      let matched = LANGUAGES.find(l => l.code.toLowerCase() === clean);
      if (matched) return { code: matched.code, language: matched, autoDetected: true };

      // Base language code match (e.g. "es-ES" -> "es", "en-US" -> "en", "fr-CA" -> "fr")
      const baseCode = clean.split('-')[0].split('_')[0];
      matched = LANGUAGES.find(l => l.code.toLowerCase() === baseCode);
      if (matched) return { code: matched.code, language: matched, autoDetected: true };
    }
  }

  // Default fallback to English
  const defaultLang = LANGUAGES[0];
  return { code: 'en', language: defaultLang, autoDetected: true };
}

interface LanguageContextType {
  language: string;
  languageData: Language;
  isAutoDetected: boolean;
  isRTL: boolean;
  setLanguage: (code: string) => Promise<void>;
  resetToDeviceLanguage: () => Promise<void>;
  t: (key: string, defaultText?: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [languageState, setLanguageState] = useState<{
    code: string;
    language: Language;
    isAuto: boolean;
  }>(() => {
    const initial = detectBrowserLanguage();
    return {
      code: initial.code,
      language: initial.language,
      isAuto: initial.autoDetected
    };
  });

  const applyLanguageEffects = useCallback((code: string, isRtl?: boolean) => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = code;
      document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    }
  }, []);

  // Set and persist language
  const setLanguage = useCallback(async (code: string) => {
    const matched = LANGUAGES.find(l => l.code.toLowerCase() === code.toLowerCase()) || LANGUAGES[0];
    
    // 1. Update React state
    setLanguageState({
      code: matched.code,
      language: matched,
      isAuto: false
    });

    // 2. Persist locally in localStorage
    try {
      localStorage.setItem('imchat_language', matched.code);
      localStorage.setItem('imchat_language_name', matched.name);
      localStorage.setItem('imchat_language_native', matched.nativeName);
    } catch (e) {
      console.warn("Could not save language to localStorage:", e);
    }

    // 3. Update document attributes
    applyLanguageEffects(matched.code, matched.rtl);

    // 4. Update Firestore user document if user is authenticated
    if (auth.currentUser) {
      try {
        const userRef = doc(db, 'users', auth.currentUser.uid);
        await updateDoc(userRef, {
          language: matched.code,
          languageName: matched.name,
          languageNativeName: matched.nativeName
        });
      } catch (err) {
        console.warn("Could not update user language in Firestore:", err);
      }
    }

    // 5. Dispatch event for external components
    window.dispatchEvent(new CustomEvent('imchat-language-changed', {
      detail: { code: matched.code, language: matched }
    }));
  }, [applyLanguageEffects]);

  // Reset to auto-detected device language
  const resetToDeviceLanguage = useCallback(async () => {
    try {
      localStorage.removeItem('imchat_language');
    } catch (e) {}
    const auto = detectBrowserLanguage();
    await setLanguage(auto.code);
    setLanguageState(prev => ({ ...prev, isAuto: true }));
  }, [setLanguage]);

  // Initial effect on mount: apply lang and RTL
  useEffect(() => {
    applyLanguageEffects(languageState.code, languageState.language.rtl);
  }, [languageState.code, languageState.language.rtl, applyLanguageEffects]);

  // Sync with Firestore profile when user logs in or profile loads
  useEffect(() => {
    const unsub = auth.onAuthStateChanged(async (currentUser) => {
      if (currentUser) {
        try {
          const userDoc = await getDoc(doc(db, 'users', currentUser.uid));
          if (userDoc.exists()) {
            const data = userDoc.data();
            if (data.language && data.language !== languageState.code) {
              const matched = LANGUAGES.find(l => l.code.toLowerCase() === data.language.toLowerCase());
              if (matched) {
                setLanguageState({
                  code: matched.code,
                  language: matched,
                  isAuto: false
                });
                localStorage.setItem('imchat_language', matched.code);
                applyLanguageEffects(matched.code, matched.rtl);
              }
            } else if (!data.language) {
              // Store current detected or selected language into user profile
              updateDoc(doc(db, 'users', currentUser.uid), {
                language: languageState.code,
                languageName: languageState.language.name,
                languageNativeName: languageState.language.nativeName
              }).catch(() => {});
            }
          }
        } catch (err) {
          console.warn("Auth language sync check:", err);
        }
      }
    });

    return () => unsub();
  }, [applyLanguageEffects, languageState.code, languageState.language]);

  // Translation function with graceful hierarchical fallbacks
  const t = useCallback((key: string, defaultText?: string): string => {
    const currentCode = languageState.code;
    
    // 1. Direct language code dictionary match
    if (TRANSLATIONS[currentCode] && TRANSLATIONS[currentCode][key]) {
      return TRANSLATIONS[currentCode][key];
    }

    // 2. Base code match (e.g. "zh-TW" -> "zh")
    const baseCode = currentCode.split('-')[0].split('_')[0];
    if (TRANSLATIONS[baseCode] && TRANSLATIONS[baseCode][key]) {
      return TRANSLATIONS[baseCode][key];
    }

    // 3. Fallback to English dictionary
    if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
      return TRANSLATIONS['en'][key];
    }

    // 4. Default provided text or key
    return defaultText || key;
  }, [languageState.code]);

  return (
    <LanguageContext.Provider value={{
      language: languageState.code,
      languageData: languageState.language,
      isAutoDetected: languageState.isAuto,
      isRTL: !!languageState.language.rtl,
      setLanguage,
      resetToDeviceLanguage,
      t
    }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    // Graceful fallback if used outside of provider
    const detected = detectBrowserLanguage();
    return {
      language: detected.code,
      languageData: detected.language,
      isAutoDetected: detected.autoDetected,
      isRTL: !!detected.language.rtl,
      setLanguage: async () => {},
      resetToDeviceLanguage: async () => {},
      t: (key: string, defaultText?: string) => defaultText || key
    };
  }
  return context;
}
